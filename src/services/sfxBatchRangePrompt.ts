用户填写的描述、关键词是本次复核的关注重点，优先完善该音效；其他内容仅补充与它明显独立且新触发的必要事件。静态海滩、背景插画、装饰、文字常驻不额外推断海浪/风声等环境底声；已有持续运动、循环闪烁也不作为新增音效。框选范围不代表其中每个视觉元素都需要配声。
